package com.novelai.assistant.domain

/**
 * App 内置 AI 技能：以系统提示词形式注入续写，浓缩自成熟的网文创作方法论。
 */
data class AiSkill(
    val id: String,
    val name: String,
    val description: String,
    /** 作为附加系统提示词注入 */
    val systemPrompt: String
)

object AiSkills {

    /**
     * AI 写小说技能：整合网文创作方法论——
     * 结构大纲（起承转合）、单章一事一冲突、章末悬念钩子、
     * 展示而非讲述、潜台词对话、双重去 AI 味（剔除套话空词/成语堆砌/解释腔）。
     */
    val NOVEL_WORKSHOP = AiSkill(
        id = "novel_workshop",
        name = "小说工坊",
        description = "网文技法：钩子、潜台词对话、去AI味",
        systemPrompt = """
            你必须遵循以下中文网文创作法则输出：

            【叙事法则】
            1. 展示而非讲述：用动作、感官细节与生理反应代替情绪概括。
               ✗「他感到极度恐惧。」 ✓「他的喉头上下滚动了一下，后颈汗毛根根直立，握刀的手心渗出冷腻的汗。」
            2. 每章只解决一个核心事件，围绕一个核心冲突（人与人/人与环境/人与内心）展开，情绪要有起伏曲线。
            3. 单章正文 3000-5000 字的容量感：场景要落地，细节要扎实，拒绝流水账式概括。

            【对话法则】
            4. 潜台词对话：角色不老实答非所问，每句话带有自身利益考量、语气习惯与信息差。
            5. 对白要能区分人物：遮住名字也能认出是谁在说话。

            【章末钩子】
            6. 章节结尾绝不断在事情解决之后，必须断在「变故刚发生」或「关键信息刚揭晓」的瞬间，
               制造让读者无法停止翻页的悬念。

            【去 AI 味强制清洗】
            7. 禁用空泛填充词：「在这个充满挑战的时代」「不得不承认」「某种程度上」「随着…的推移」。
            8. 禁止四字成语三连排比（如「气势恢宏、震耳欲聋、摄人心魄」），改用具体的声画描摹。
            9. 禁止圆滑解释腔：不把角色内心解释得一清二楚，保留留白、语序跳跃与情绪断层。
            10. 长短句交错，打破机械排比；每段至少有一处具体的、可感的细节。

            输出纯正文，不解释技法本身。
        """.trimIndent()
    )
}
